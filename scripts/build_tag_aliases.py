"""Build the browser tag map from the API's shared aliases."""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    aliases = json.loads((root / "backend/app/tag_aliases.json").read_text())
    if not isinstance(aliases, dict) or not aliases:
        raise SystemExit("Tag aliases must be a nonempty object")
    for alias, canonical in aliases.items():
        if not isinstance(alias, str) or not alias or not isinstance(canonical, str) or not canonical:
            raise SystemExit("Tag names must be nonempty strings")
        if aliases.get(canonical) != canonical:
            raise SystemExit(f"Tag alias is not canonical: {alias}")
    output = "// Generated by scripts/build_tag_aliases.py. Do not edit.\n"
    output += "window.ResearchScopeTagAliases = Object.freeze(Object.assign(Object.create(null), "
    output += json.dumps(aliases, indent=2, ensure_ascii=True) + "));\n"
    target = root / "site/assets/js/tag-aliases.js"
    if args.check:
        if not target.is_file() or target.read_text() != output:
            raise SystemExit("Run python scripts/build_tag_aliases.py to update browser aliases")
    else:
        target.write_text(output)


if __name__ == "__main__":
    main()
